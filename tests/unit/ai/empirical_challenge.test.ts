  describe("Challenge 3: Concurrency Limiting vs Geoapify 5 RPS Rate Limit", () => {
    it("empirically demonstrates that ConcurrencyLimiter(4) violates Geoapify 5 RPS limit", async () => {
      // Simulate ConcurrencyLimiter(4) on 20 requests
      class ConcurrencyLimiter {
        private active = 0;
        private queue: Array<() => void> = [];
        constructor(private limit: number) {}
        async run<T>(fn: () => Promise<T>): Promise<T> {
          if (this.active >= this.limit) {
            await new Promise<void>((resolve) => this.queue.push(resolve));
          }
          this.active++;
          try {
            return await fn();
          } finally {
            this.active--;
            if (this.queue.length > 0) {
              const next = this.queue.shift();
              next?.();
            }
          }
        }
      }

      const limiter = new ConcurrencyLimiter(4);
      const requestTimestamps: number[] = [];

      // Mock place request taking ~30ms (simulating fast API response or cached network)
      const mockApiCall = async (id: number) => {
        requestTimestamps.push(Date.now());
        await new Promise((resolve) => setTimeout(resolve, 30));
        return { id, ok: true };
      };

      const startTime = Date.now();
      await Promise.all(
        Array.from({ length: 20 }, (_, i) => limiter.run(() => mockApiCall(i)))
      );
      const totalElapsedMs = Date.now() - startTime;
      expect(totalElapsedMs).toBeGreaterThan(0);

      // Calculate peak requests per second in any 1000ms window
      let maxReqInOneSecond = 0;
      for (const t of requestTimestamps) {
        const count = requestTimestamps.filter((other) => other >= t && other < t + 1000).length;
        if (count > maxReqInOneSecond) maxReqInOneSecond = count;
      }

      // Geoapify Free Tier allows max 5 requests per second.
      // With ConcurrencyLimiter(4) and fast/cached responses:
      expect(maxReqInOneSecond).toBeGreaterThan(5);
      // Notice: 20 requests finished in ~200ms, representing a rate of ~100 RPS!
      // Pure Concurrency Limiting without a Rate Limiter (token bucket or min interval)
      // blows past Geoapify's 5 RPS limit immediately!
    });
  });

